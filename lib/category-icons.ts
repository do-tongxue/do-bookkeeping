export function categoryIconFor(category: string, type: EntryType): LucideIcon {
  const name = category.normalize("NFKC").trim()
  if (name === "其他") return type === "income" ? CircleDollarSign : ReceiptText
  if (ICONS[name]) return ICONS[name]
  return CATEGORY_ALIASES.find(([pattern]) => pattern.test(name))?.[1] ?? Tags
}
